// The house executor. The gold CTA and the AI Agent call the same function, which
// signs with the visitor's own session key on the board and never opens a wallet.
//
// Every write goes through the board: propose_call_as is the only door, the board
// writes row_owner, and the house contract checks that the predecessor is the board.
// The session key cannot call the house directly, so a visitor's key never becomes a
// house key and the row's cap/budget/receivers still apply.
//
// The message text is assembled by app/src/house-board.js, which mirrors
// contracts/charter_board/src/v2.rs. Repeating an action id does not pay twice
// (the house contract keeps a `seen` map and the board refuses a repeated action).
//
// https://docs.near.org/protocol/accounts-contracts/access-keys
// https://docs.near.org/protocol/transactions/gas#buying-vs-burning-gas
import { proposeCallAs } from './house-board.js';

/**
 * The wallet layer, injected once per environment. The browser passes the built
 * wallet bundle; node tests pass the same functions from shared/vault/tx.js.
 * A static import would break `node --test` because wallet.bundle.js is generated
 * by app/build.mjs and is not in the source tree.
 */
export let W = null;
export function setWallet(wallet) { W = wallet; }

/** The built wallet bundle, loaded on first use. It is generated by app/build.mjs, so a
 *  static import would fail under `node --test` where the file does not exist. */
export async function loadWallet() {
  if (W) return W;
  if (typeof globalThis.document === 'undefined') return null;
  try {
    const mod = await import('../../design/D8_shops/js/wallet.bundle.js');
    W = mod;
    return W;
  } catch { return null; }
}

/** The wallet when it is already loaded. Callers that must not await use this. */
export function houseWallet() { return W; }

export const TG = 10n ** 12n;
/** Prepaid gas for one propose_call_as. The house callback is small; the board is the cost. */
export const CALL_AS_TGAS = 150n;

/** Why a signer cannot act, or '' when it can. Never returns a secret. */
export function signerBlocker({ key, row, board, accessKey, gasTgas = CALL_AS_TGAS }) {
  if (!key) return 'Set up your agent in /setup. Nothing was signed.';
  if (!row) return 'Your row is not loaded. Nothing was signed.';
  if (!W) return 'The wallet is not loaded. Nothing was signed.';
  if (W.pubkeyHex(key) !== String(row.agent || '')) return 'This browser is not the agent on the row. Nothing was signed.';
  if (!accessKey) return 'The session key was not found. Renew it in /setup. Nothing was signed.';
  const perm = accessKey.permission?.FunctionCall;
  if (!perm || perm.receiver_id !== board) return 'The session key is not for the board. Renew it in /setup. Nothing was signed.';
  const names = perm.method_names || [];
  if (names.length && !names.includes('propose_call_as')) {
    return 'This key can call propose. It cannot call propose_call_as. Renew it in /setup. Nothing was signed.';
  }
  const allowance = BigInt(perm.allowance || 0);
  // Gas is bought at 0.001 NEAR/Tgas; the allowance must cover the whole prepaid amount.
  const need = gasTgas * 10n ** 21n;
  if (allowance < need) return 'The session key allowance cannot buy this call. Renew it in /setup. Nothing was signed.';
  return '';
}

/** The visitor's own agent key from this browser's slot, read at click time. */
export function browserKey(account) {
  return account && W ? W.storedAgentKey(k => globalThis.localStorage?.getItem(k), account) : null;
}

/** The session access key on the board, or null. `finality: optimistic` is what the other shops read. */
export async function boardAccessKey(rpc, account, key) {
  if (!rpc || !account || !key) return null;
  const ak = await rpc('query', { request_type: 'view_access_key', finality: 'optimistic', account_id: account, public_key: key.publicKey }).catch(() => null);
  const perm = ak?.permission?.FunctionCall;
  return perm && ak ? ak : null;
}

/**
 * Sign and send one house call through the board.
 * Returns { ok, tx, decision, reason, signer } or throws with a reason.
 * `build` is a house-board proposeCallAs result (unsigned).
 */
export async function sendHouseCall({ rpc, key, accessKey, me, board, build, gasTgas = CALL_AS_TGAS }) {
  if (!key || !accessKey) throw new Error('No session key. Nothing was signed.');
  if (!W) throw new Error('The wallet is not loaded. Nothing was signed.');
  const signature = W.signMessage(key, build.message);
  const call = { ...build.args, signature };
  const signed = W.signTx({
    key,
    signerId: me,
    receiverId: board,
    nonce: BigInt(accessKey.nonce) + 1n,
    blockHash: accessKey.block_hash,
    actions: [W.functionCall('propose_call_as', call, gasTgas * TG)],
  });
  const sent = W.outcomeOf(await rpc('send_tx', { signed_tx_base64: signed.base64, wait_until: 'FINAL' }));
  if (!sent.ok) {
    return { ok: false, tx: signed.hash, decision: 'denied', reason: String(sent.error || 'refused').slice(0, 160), signer: 'agent' };
  }
  return { ok: true, tx: signed.hash, decision: 'allowed', reason: 'ok', signer: 'agent' };
}

/**
 * The four house writes. Each returns an unsigned board call plus the executor.
 * `kind`: mint | checkin | setline | pay | prepare.
 * Context is the visitor's own: account, board, row (nonce/epoch/min_amount), token id.
 */
export function houseCall({ kind, ctx, params = {} }) {
  const { account, board, row, tokenId, network = 'mainnet' } = ctx || {};
  if (!account) throw new Error('Sign in first. Nothing was signed.');
  if (!board) throw new Error('The board is not configured. Nothing was signed.');
  if (!row || row.nonce == null) throw new Error('Your row is not loaded. Nothing was signed.');
  const nonce = String(row.nonce);
  const epoch = String(row.epoch ?? '0');
  const min = row.min_amount != null && row.min_amount !== '' ? String(row.min_amount) : '0';
  // The board takes the spend deposit from the row; a rule with no minimum still needs 1 yocto.
  const deposit = BigInt(min) > 0n ? String(BigInt(min)) : '1';
  const house = ctx.house;
  if (!house) throw new Error('The house shop is not configured. Nothing was signed.');
  const expiry = (BigInt(Date.now()) * 1_000_000n + 600_000_000_000n).toString();

  const base = { network, board, owner: account, receiver: house, deposit, expiry, nonce, epoch };

  if (kind === 'mint') {
    const cap = params.cap ? String(params.cap) : '50000000000000000000000';
    return proposeCallAs({ ...base, method: 'house_session_mint', args: { row_owner: account, cap }, effects: [], hold: false });
  }
  if (!tokenId) throw new Error('This account has no deed yet. Mint first. Nothing was signed.');
  if (kind === 'checkin') {
    return proposeCallAs({ ...base, method: 'house_session_check_in', args: { row_owner: account, token_id: tokenId }, effects: [], hold: false });
  }
  if (kind === 'setline') {
    const heirs = (params.heirs || []).map(String);
    const guardians = (params.guardians || []).map(String);
    if (!heirs.length || !guardians.length) throw new Error('Name one heir and one guardian. Nothing was signed.');
    const threshold = Number(params.threshold || 1);
    const period = String(params.periodNs || 0);
    const wait = String(params.waitNs || 0);
    return proposeCallAs({
      ...base,
      method: 'house_session_set_line',
      args: { row_owner: account, token_id: tokenId, heirs, guardians, threshold, period_ns: period, wait_ns: wait },
      effects: [],
      hold: false,
    });
  }
  if (kind === 'pay') {
    const receiver = String(params.receiver || '');
    const amount = String(params.amount || '0');
    if (!receiver || !/^\d+$/.test(amount) || amount === '0') throw new Error('Name a payee and an amount. Nothing was signed.');
    return proposeCallAs({
      ...base,
      method: 'house_session_pay',
      args: { row_owner: account, token_id: tokenId, receiver_id: receiver, amount, action_id: String(params.actionId || `${tokenId}|pay|${receiver}|${amount}`) },
      // A NEAR purse payment moves NEAR and no foreign asset, so the effect list stays empty.
      effects: [],
      hold: false,
    });
  }
  if (kind === 'prepare') {
    const chain = String(params.chain || 'base');
    const asset = String(params.asset || 'ETH');
    const to = String(params.to || '');
    const value = String(params.value || '0');
    const gasLimit = Number(params.gasLimit || 21000);
    if (chain === 'btc' && BigInt(value) > 0n) throw new Error('Bitcoin is signing only. Nothing was signed.');
    return proposeCallAs({
      ...base,
      method: 'house_session_prepare_send',
      args: { row_owner: account, token_id: tokenId, chain, to, asset, value, gas_limit: gasLimit, action_id: String(params.actionId || `${tokenId}|prepare|${chain}|${to}|${value}`) },
      effects: [{ chain, asset, to, value, fee: '0' }],
      hold: true,
    });
  }
  throw new Error('Unknown house action. Nothing was signed.');
}
