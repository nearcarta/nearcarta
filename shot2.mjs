import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 2 });
p.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text().slice(0,160)); });
p.on('pageerror', e => console.log('PAGEERROR', e.message.slice(0,200)));
await p.goto('http://127.0.0.1:5173/?shop=guard', { waitUntil: 'load', timeout: 60000 });
await p.waitForTimeout(12000);
console.log('title:', await p.title());
console.log('body text:', (await p.locator('body').innerText()).slice(0, 900));
await p.screenshot({ path: '/tmp/shots/guard2.png' });
await b.close();
