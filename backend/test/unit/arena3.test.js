import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { pastPrompts, ARENA } from '../../src/arena.js';
import { MAINNET_DEP } from '../../src/config.js';
import { PAST3, ARENA3 } from '../../../shared/arena/prompts3.js';
const sha = s => createHash('sha256').update(s).digest('hex');
test('the served arena is the mainnet arena and is read once', async () => {
  assert.equal(ARENA, 'arena.nearcarta.near');
  assert.equal(ARENA, ARENA3);
  assert.equal(MAINNET_DEP.extras.arena.contract, ARENA);
  const chain = PAST3.map(p => ({ player: 'p', token_id: 'g1', prompt_hash_hex: p.prompt ? sha(p.prompt) : 'x', verdict: p.verdict, revealed: !!p.prompt }));
  const seen = [];
  const body = await pastPrompts(async (C, m, { attempt_id }) => { seen.push(C); return chain[attempt_id] || null; }, 1);
  assert.equal(body.contract, ARENA);
  assert.equal(body.history_contract, null);
  assert.ok(body.prompts.filter(p => p.prompt).length >= 8);
  assert.ok(body.prompts.every(p => p.contract === ARENA));
  assert.ok(seen.every(C => C === ARENA));
});
